#!/usr/bin/env python3
"""Generate nw4r_g3d_calcvtx.txt: CalcVtx with its paired-single blocks written in C.

CalcVtx is long and its assembly is six small blocks repeated three times, so the port
version is derived from the original rather than written out by hand. Rerun after any
change to the original function.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "tools"))
import port_replace as pr

SRC = "src/nw4r/g3d/g3d_calcvtx.cpp"

def block(*instrs):
    """Regex for `asm { <instrs> }` with any spacing."""
    body = r"\s*".join(r"\s+".join(map(re.escape, i.split())).replace(r"\,", r"\s*,\s*").replace(",", r"\s*,\s*") for i in instrs)
    return re.compile(r"asm\s*\{\s*" + body + r"\s*\}")

REWRITES = [
    # Declarations of paired registers become scalars.
    (re.compile(r"register f32 xy, z_;"), "f32 x, y, z_;"),
    (re.compile(r"register f32 rg, ba;"), "f32 r, g, b, a;"),
    (re.compile(r"\n[ \t]*register f32 key_xy, key_z_;"), ""),
    (re.compile(r"\n[ \t]*register f32 key_rg, key_ba;"), ""),
    # VEC3: first key times its weight, further keys fused-multiply-added, then stored.
    (block("psq_l xy, VEC3.x(pVtx), 0, 0", "psq_l z_, VEC3.z(pVtx), 1, 0", "ps_mul xy, xy, firstWeight", "ps_mul z_, z_, firstWeight"),
     "{\n                    const math::VEC3* pV = static_cast<const math::VEC3*>(pVtx);\n"
     "                    x = pV->x * firstWeight;\n                    y = pV->y * firstWeight;\n                    z_ = pV->z * firstWeight;\n                }"),
    (block("psq_l key_xy, VEC3.x(pKeyVtx), 0, 0", "psq_l key_z_, VEC3.z(pKeyVtx), 1, 0", "ps_madd xy, key_xy, keyWeight, xy", "ps_madd z_, key_z_, keyWeight, z_"),
     "{\n                        const math::VEC3* pK = static_cast<const math::VEC3*>(pKeyVtx);\n"
     "                        x = __builtin_fmaf(pK->x, keyWeight, x);\n                        y = __builtin_fmaf(pK->y, keyWeight, y);\n"
     "                        z_ = __builtin_fmaf(pK->z, keyWeight, z_);\n                    }"),
    (block("psq_st xy, VEC3.x(pDst), 0, 0", "psq_st z_, VEC3.z(pDst), 1, 0"),
     "{\n                    math::VEC3* pD = static_cast<math::VEC3*>(pDst);\n"
     "                    pD->x = x;\n                    pD->y = y;\n                    pD->z = z_;\n                }"),
    # Colors: quantised u8 loads (GQR2) and saturating, truncating u8 stores.
    (block("psq_l rg, Color.r(pVtx), 0, 2", "psq_l ba, Color.b(pVtx), 0, 2", "ps_mul rg, rg, firstWeight", "ps_mul ba, ba, firstWeight"),
     "{\n                    const ut::Color* pC = static_cast<const ut::Color*>(pVtx);\n"
     "                    r = pC->r * firstWeight;\n                    g = pC->g * firstWeight;\n"
     "                    b = pC->b * firstWeight;\n                    a = pC->a * firstWeight;\n                }"),
    (block("psq_l key_rg, Color.r(pKeyVtx), 0, 2", "psq_l key_ba, Color.b(pKeyVtx), 0, 2", "ps_madd rg, key_rg, keyWeight, rg", "ps_madd ba, key_ba, keyWeight, ba"),
     "{\n                        const ut::Color* pK = static_cast<const ut::Color*>(pKeyVtx);\n"
     "                        r = __builtin_fmaf(pK->r, keyWeight, r);\n                        g = __builtin_fmaf(pK->g, keyWeight, g);\n"
     "                        b = __builtin_fmaf(pK->b, keyWeight, b);\n                        a = __builtin_fmaf(pK->a, keyWeight, a);\n                    }"),
    (block("psq_st rg, Color.r(pDst), 0, 2", "psq_st ba, Color.b(pDst), 0, 2"),
     "{\n                    ut::Color* pD = static_cast<ut::Color*>(pDst);\n"
     "                    pD->r = __OSf32tou8(r);\n                    pD->g = __OSf32tou8(g);\n"
     "                    pD->b = __OSf32tou8(b);\n                    pD->a = __OSf32tou8(a);\n                }"),
]

def main():
    path = pr.DECOMP / SRC
    lines = path.read_text(encoding="utf-8").split("\n")
    first, last = pr.find_definition(lines, "CalcVtx", 1)
    text = "\n".join(lines[first:last + 1])
    for pattern, replacement in REWRITES:
        text, count = pattern.subn(lambda _m, r=replacement: r, text)
        if count == 0:
            raise SystemExit(f"pattern not found: {pattern.pattern[:80]}")
    if re.search(r"\basm\b", text):
        raise SystemExit("assembly left in the generated CalcVtx")
    out = HERE / "nw4r_g3d_calcvtx.txt"
    out.write_text("# Generated by gen_g3d_calcvtx.py from the original CalcVtx; do not edit.\n\n"
                   f"@@ {SRC} CalcVtx\n{text}\n", encoding="utf-8")
    print(f"wrote {out.relative_to(HERE.parents[1])}")

if __name__ == "__main__":
    main()
