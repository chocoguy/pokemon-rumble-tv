#!/usr/bin/env python3
"""Generate nw4r_g3d_calcworld.txt: CalcSkinning with its paired-single blocks in C.

Each output matrix is the weighted sum of its bone matrices: M = sum(R_i * T_i), summed
with fused multiply-adds like ps_madds0. Rerun after any change to the original.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "tools"))
sys.path.insert(0, str(HERE))
import port_replace as pr
from gen_g3d_calcvtx import block

SRC = "src/nw4r/g3d/g3d_calcworld.cpp"

REWRITES = [
    (re.compile(r"register f32 M00, M02;\s*register f32 M10, M12;\s*register f32 M20, M22;\s*M00 = 0\.0f;"),
     "f32 M[12];"),
    (block("ps_merge00 M00, M00, M00", "ps_merge00 M02, M00, M00", "ps_merge00 M10, M00, M00",
           "ps_merge00 M12, M00, M00", "ps_merge00 M20, M00, M00", "ps_merge00 M22, M00, M00"),
     "for (int k = 0; k < 12; k++) {\n                M[k] = 0.0f;\n            }"),
    (re.compile(r"\n[ \t]*register f32 T00, T02;\s*register f32 T10, T12;\s*register f32 T20, T22;\n"), "\n"),
    (block("psq_l T00, MTX34._00(pT), 0, 0", "psq_l T02, MTX34._02(pT), 0, 0", "psq_l T10, MTX34._10(pT), 0, 0",
           "psq_l T12, MTX34._12(pT), 0, 0", "psq_l T20, MTX34._20(pT), 0, 0", "psq_l T22, MTX34._22(pT), 0, 0",
           "ps_madds0 M00, T00, R, M00", "ps_madds0 M02, T02, R, M02", "ps_madds0 M10, T10, R, M10",
           "ps_madds0 M12, T12, R, M12", "ps_madds0 M20, T20, R, M20", "ps_madds0 M22, T22, R, M22"),
     "{\n                    const f32* pTf = &pT->_00;\n                    for (int k = 0; k < 12; k++) {\n"
     "                        M[k] = __builtin_fmaf(pTf[k], R, M[k]);\n                    }\n                }"),
    (block("psq_st M00, MTX34._00(pTargetMtx), 0, 0", "psq_st M02, MTX34._02(pTargetMtx), 0, 0",
           "psq_st M10, MTX34._10(pTargetMtx), 0, 0", "psq_st M12, MTX34._12(pTargetMtx), 0, 0",
           "psq_st M20, MTX34._20(pTargetMtx), 0, 0", "psq_st M22, MTX34._22(pTargetMtx), 0, 0"),
     "{\n                f32* pD = &pTargetMtx->_00;\n                for (int k = 0; k < 12; k++) {\n"
     "                    pD[k] = M[k];\n                }\n            }"),
]

def main():
    path = pr.DECOMP / SRC
    lines = path.read_text(encoding="utf-8").split("\n")
    first, last = pr.find_definition(lines, "CalcSkinning", 1)
    text = "\n".join(lines[first:last + 1])
    for pattern, replacement in REWRITES:
        text, count = pattern.subn(lambda _m, r=replacement: r, text)
        if count == 0:
            raise SystemExit(f"pattern not found: {pattern.pattern[:80]}")
    if re.search(r"\basm\b", text):
        raise SystemExit("assembly left in the generated CalcSkinning")
    out = HERE / "nw4r_g3d_calcworld.txt"
    out.write_text("# Generated by gen_g3d_calcworld.py from the original CalcSkinning; do not edit.\n\n"
                   f"@@ {SRC} CalcSkinning\n{text}\n", encoding="utf-8")
    print(f"wrote {out.relative_to(HERE.parents[1])}")

if __name__ == "__main__":
    main()
