#!/usr/bin/env python3
"""Generate link stubs for every symbol the port does not implement yet.

    tools/gen_link_stubs.py --sdk macosx --out build/link_stubs.c lib1.a lib2.a ...

A symbol needs a stub when some object in the archives references it, no object defines
it, and the platform's system libraries (read from the SDK's .tbd export lists) do not
export it. Each stub:

  - a function logs "[RED] unimplemented <name>" to stderr the first time it is called
    and returns 0;
  - a variable is 4 KB of zeroed, 64-byte aligned storage.

Functions and variables are told apart by demangling C++ names (variables have no
parameter list) and, for C names, by the type in the decomp's symbol map. The list is
also written next to the output (.txt), one name per line, sorted: it is the port's
to-do list, and it shrinks as port/ implements the SDK.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SYMBOLS = ROOT / "pokemon-rumble-decomp-tv/config/wpse-v1/symbols.txt"

# System libraries the port links against; their exports never need a stub.
SYSTEM_TBDS = ["usr/lib/libSystem.B.tbd", "usr/lib/libc++.1.tbd", "usr/lib/libc++abi.tbd", "usr/lib/libobjc.A.tbd"]


def sdk_path(sdk):
    return Path(subprocess.check_output(["xcrun", "--sdk", sdk, "--show-sdk-path"], text=True).strip())


def tbd_exports(paths):
    names = set()
    for path in paths:
        text = path.read_text(encoding="utf-8", errors="replace")
        for block in re.findall(r"(?:symbols|weak-symbols|thread-local-symbols|objc-classes|objc-ivars|objc-eh-types):\s*\[([^\]]*)\]", text):
            for name in block.split(","):
                name = name.strip().strip("'\"")
                if name:
                    names.add(name)
        # objc classes appear without the leading underscore and _OBJC_CLASS_$_ prefix
    return names


def archive_symbols(archives):
    defined, undefined = set(), set()
    for archive in archives:
        out = subprocess.run(["xcrun", "nm", "-g", "-P", str(archive)], capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) < 2 or line.endswith(":"):
                continue
            name, kind = parts[0], parts[1]
            if kind == "U":
                undefined.add(name)
            else:
                defined.add(name)
    return defined, undefined


def c_symbol_kinds():
    kinds = {}
    for line in SYMBOLS.read_text(encoding="utf-8").splitlines():
        m = re.match(r"(\S+) = \S+; // type:(\w+)", line)
        if m:
            kinds[m.group(1)] = m.group(2)
    return kinds


def demangle(names):
    if not names:
        return {}
    out = subprocess.run(["xcrun", "c++filt", "-_"], input="\n".join(names), capture_output=True, text=True).stdout.splitlines()
    return dict(zip(names, out))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sdk", default="macosx")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("archives", nargs="+", type=Path)
    args = parser.parse_args()

    sdk = sdk_path(args.sdk)
    system = set()
    tbds = [sdk / t for t in SYSTEM_TBDS] + sorted((sdk / "usr/lib/system").glob("*.tbd"))
    system = tbd_exports([t for t in tbds if t.exists()])
    defined, undefined = archive_symbols(args.archives)
    # The linker itself provides these.
    linker_provided = {"___dso_handle", "__mh_execute_header", "__mh_dylib_header"}
    missing = sorted(n for n in undefined - defined - system - linker_provided)

    kinds = c_symbol_kinds()
    cxx = [n for n in missing if n.startswith("__Z")]
    names = demangle(cxx)

    funcs, datas = [], []
    for name in missing:
        if name.startswith("__Z"):
            readable = names.get(name, name)
            is_func = "(" in readable and not readable.startswith(("vtable for", "typeinfo for", "typeinfo name for"))
        else:
            c_name = name[1:] if name.startswith("_") else name
            readable = c_name
            if c_name in kinds:
                is_func = kinds[c_name] == "function"
            else:
                # Port and game globals follow the gName / sName convention.
                is_func = not re.match(r"[gs][A-Z]", c_name)
        (funcs if is_func else datas).append((name, readable))

    lines = [
        "/* Generated by tools/gen_link_stubs.py: symbols the port does not implement yet. */",
        "#include <stdio.h>",
        "",
        "static void PortStubReport(const char* name, int* reported) {",
        "    if (!*reported) {",
        "        *reported = 1;",
        '        fprintf(stderr, "[RED] unimplemented %s\\n", name);',
        "    }",
        "}",
        "",
    ]
    for i, (name, readable) in enumerate(funcs):
        label = name[1:] if name.startswith("_") else name
        text = readable.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'static int sStubReported{i};')
        lines.append(f'long PortStub{i}(void) __asm__("{name}");')
        lines.append(f'long PortStub{i}(void) {{ PortStubReport("{text}", &sStubReported{i}); return 0; }}')
    for i, (name, readable) in enumerate(datas):
        lines.append(f'__attribute__((aligned(64))) unsigned char PortStubData{i}[4096] __asm__("{name}");')
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    listing = args.out.with_suffix(".txt")
    listing.write_text("".join(f"{'data' if (n, r) in datas else 'func'} {r}\n" for n, r in sorted(funcs + datas, key=lambda x: x[1])), encoding="utf-8")
    print(f"{len(funcs)} function stubs, {len(datas)} data stubs -> {args.out} (list: {listing.name})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
